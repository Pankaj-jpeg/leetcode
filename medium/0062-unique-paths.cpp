////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// Approach: combinatorial calculation | Time: O(m+n) | Space: O(1))
// Time       : 
// Space      : 
// Runtime    : 0 ms  |  Memory: 7.8 MB
// Date       : 2026-07-29
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class Solution {
public:
    int uniquePaths(int m, int n) {
        long long ans = 1;

        for(int i = m+n-2,j = 1;i>=max(m,n);i--,j++){
            ans = (ans*i)/j;
        }

        return ans;
    }
};